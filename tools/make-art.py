def launcher_icon():
    """
    The launcher mark: a chanterelle, drawn from a chosen reference.

    Three earlier attempts failed and all three failed the same way — a symmetric,
    front-on silhouette that read as wings, a tulip or a pair of quote marks. The
    reference he pointed at (a hand-drawn fly agaric, pictureboxblue) shows why: it is a
    **three-quarter view**, tilted so the eye sees the top of the cap *and* into the
    underside at once, with the gills as fine radiating hatching. That is what makes it
    read as a mushroom in one look rather than as a shape.

    So this is the same view for a chanterelle: looking slightly down into the funnel,
    wavy rim, the blunt decurrent ridges running down the front, and one confident
    outline. Outline only, per the reference — no solid fill.
    """
    W = 6.0
    inner = "".join([
        # The reference's geometry, not my idea of a chanterelle. Four attempts drew a
        # symmetric V — a vase seen dead on — and every one read as wings or a crown.
        # The fly agaric in the reference reads instantly because it is a cap *mass*
        # seen from above and in front, with a stem beneath it. So: the same, with a
        # chanterelle's wavy rim and its funnel showing.
        path("M13,41 Q15,25 33,22 Q48,15 63,22 Q82,26 84,42 "
             "Q68,55 48,56 Q26,55 13,41 Z", width=W),
        # The funnel, seen into.
        path("M30,33 Q48,44 66,32", width=W - 2.0),
        # The stem below, one shape, narrowing.
        path("M40,55 Q39,72 42,88 L54,88 Q57,72 56,55", width=W),
        # Ridges running off the near rim onto the stem.
        path("M31,53 Q30,62 31,70 M64,52 Q66,62 65,70", width=W - 2.5),
    ])
    body = (
        '    <group android:scaleX="0.75" android:scaleY="0.75"\n'
        '        android:translateX="18" android:translateY="18">\n'
        + inner +
        '    </group>\n'
    )
    head = HEADER.replace('android:width="96dp"', 'android:width="108dp"') \
                 .replace('android:height="96dp"', 'android:height="108dp"') \
                 .replace('android:viewportWidth="96"', 'android:viewportWidth="108"') \
                 .replace('android:viewportHeight="96"', 'android:viewportHeight="108"')
    with open(os.path.join(OUT, "ic_launcher_foreground.xml"), "w") as f:
        f.write(head + body + FOOTER)
    print("  launcher foreground: chanterelle, three-quarter, from the owner's reference")


def emit_kotlin():
    """
    The map the app draws from, plus what each drawing is of.

    Generated rather than hand-kept so a new drawing cannot be added without its
    provenance, and so the two can never drift apart.
    """
    rows = []
    for name in sorted(EXEMPLARS):
        if name.startswith("art_launcher"):
            continue
        body = name[len("art_"):]
        species, why = EXEMPLARS[name]
        # Longest character id wins, so gill_edge does not swallow gill_edge_even.
        rows.append((body, name, species, why))

    def split(body):
        for cid in sorted(CHARACTERS, key=len, reverse=True):
            if body.startswith(cid + "_"):
                return cid, body[len(cid) + 1:]
        raise SystemExit(f"cannot split {body}")

    lines = [
        "package com.wanderwildwood.kinokocho.ui",
        "",
        "import com.wanderwildwood.kinokocho.R",
        "",
        "/**",
        " * The drawing for a character state, and the mushroom it was drawn from.",
        " *",
        " * Generated by tools/make-art.py. Do not edit by hand.",
        " *",
        " * Naming the species is not the app identifying anything — it is saying what the",
        " * picture is of, the way a field guide captions a plate. A reader who wants to know",
        " * why decurrent looks like that gets an answer; the mushroom in their hand is never",
        " * named by this app.",
        " */",
        "data class Art(val drawable: Int, val species: String?, val note: String)",
        "",
        "object CharacterArt {",
        "",
        "    private val byState: Map<String, Art> = mapOf(",
    ]
    for body, name, species, why in rows:
        cid, vid = split(body)
        sp = "null" if species == "—" else f"\"{species}\""
        lines.append(f'        "{cid}/{vid}" to Art(R.drawable.{name}, {sp}, "{why}"),')
    lines += [
        "    )",
        "",
        "    /** The drawing for a state, or null where none has been drawn yet. */",
        "    fun of(characterId: String, valueId: String): Art? = byState[\"$characterId/$valueId\"]",
        "",
        "    /** True when every state of a character has a drawing, so a grid is safe. */",
        "    fun coversAll(characterId: String, valueIds: List<String>): Boolean =",
        "        valueIds.isNotEmpty() && valueIds.all { byState.containsKey(\"$characterId/$it\") }",
        "}",
        "",
    ]
    os.makedirs(os.path.dirname(KT), exist_ok=True)
    with open(KT, "w") as f:
        f.write("\n".join(lines))


