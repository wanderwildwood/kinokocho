# Anatomy shared between drawings, so a stem is the same stem everywhere.

def ground(x1=10, x2=86, y=GROUND):
    return path(f"M{x1},{y} L{x2},{y}", width=FINE)


def stem_sides(x=48, top=48, bottom=GROUND, half=6):
    return f"M{x - half},{top} L{x - half},{bottom} M{x + half},{top} L{x + half},{bottom}"


def capped_cap(cx=48, half=34, base=46, rise=24, flesh=5):
    """
    A cap in section, with thickness.

    Cap flesh is not a line: gills hang from a wedge of tissue, and drawing it as one
    line is what makes amateur diagrams look wrong. The lower curve is where the gills
    attach, the upper is the surface.
    """
    return (
        f"M{cx - half},{base} "
        f"Q{cx - half},{base - rise} {cx},{base - rise} "
        f"Q{cx + half},{base - rise} {cx + half},{base} "
        f"Q{cx + half - 4},{base - flesh} {cx + half - 10},{base - flesh + 1} "
        f"L{cx - half + 10},{base - flesh + 1} "
        f"Q{cx - half + 4},{base - flesh} {cx - half},{base} Z"
    )


def tilted_cap(cx=48, cy=52, rx=34, ry=13, rise=22):
    """
    A cap seen from below and in front, so the underside is a surface and not an edge.

    Which of gills, tubes, pores, teeth or ridges a mushroom has is decided by looking
    underneath. Drawn in profile the answer is a few pixels of texture on a line; tilted,
    it is most of the picture. Field guides tilt for exactly this reason.
    """
    return path(
        f"M{cx - rx},{cy} "
        f"Q{cx - rx},{cy - rise} {cx},{cy - rise} "
        f"Q{cx + rx},{cy - rise} {cx + rx},{cy} "
        f"Q{cx + rx},{cy + ry} {cx},{cy + ry} "
        f"Q{cx - rx},{cy + ry} {cx - rx},{cy} Z"
    )


def underside_rim(cx=48, cy=52, rx=34, ry=13):
    """The ellipse where the cap edge meets the underside — the near edge only."""
    return path(
        f"M{cx - rx},{cy} Q{cx - rx},{cy + ry} {cx},{cy + ry} Q{cx + rx},{cy + ry} {cx + rx},{cy}",
        width=FINE,
    )


def radiating(cx=48, cy=52, rx=34, ry=13, n=13, inner=0.18, width=FINE):
    """
    Gills or ridges on a tilted underside: lines from the centre out to the rim.

    Foreshortened by the same ellipse as the rim, so they sit on the surface rather
    than floating over it.
    """
    import math
    d = []
    for i in range(n):
        # Only the front half is visible; the back is hidden by the cap.
        t = math.pi * (i / (n - 1))
        x = cx + rx * math.cos(t) * -1
        y = cy + ry * math.sin(t)
        xi = cx + (x - cx) * inner
        yi = cy + (y - cy) * inner
        d.append(f"M{xi:.1f},{yi:.1f} L{x:.1f},{y:.1f}")
    return path(" ".join(d), width=width)


def pore_field(cx=48, cy=54, rx=30, ry=10, rows=3, per=7, r=2.6, fine=False):
    """Round tube mouths on a tilted underside — a bolete's, drawn big enough to count."""
    import math
    d = []
    for j in range(rows):
        fy = (j + 1) / (rows + 0.6)
        for i in range(per):
            ft = (i + 0.5) / per
            x = cx - rx + 2 * rx * ft
            span = math.sqrt(max(0.0, 1 - ((x - cx) / rx) ** 2))
            y = cy + ry * fy * span
            rr = r * (0.75 + 0.25 * span)
            d.append(
                f"M{x - rr:.1f},{y:.1f} "
                f"Q{x - rr:.1f},{y - rr:.1f} {x:.1f},{y - rr:.1f} "
                f"Q{x + rr:.1f},{y - rr:.1f} {x + rr:.1f},{y:.1f} "
                f"Q{x + rr:.1f},{y + rr:.1f} {x:.1f},{y + rr:.1f} "
                f"Q{x - rr:.1f},{y + rr:.1f} {x - rr:.1f},{y:.1f} Z"
            )
    return path(" ".join(d), width=HAIR if fine else FINE)


def gill_blades(cx=48, half=34, base=45, depth=10, n=8, inner=12, taper=True):
    """
    Gills seen edge-on under a cap. They are deepest at mid-radius and shallow at the
    margin, which is what makes a gilled underside read as gills and not as a comb.
    """
    d = []
    step = (half - inner) / max(n - 1, 1)
    for i in range(n):
        off = inner + i * step
        frac = 1.0 - (off - inner) / max(half - inner, 1)
        dep = depth * (0.45 + 0.55 * frac) if taper else depth
        for sign in (-1, 1):
            x = cx + sign * off
            d.append(f"M{x:.1f},{base} L{x:.1f},{base + dep:.1f}")
    return path(" ".join(d), width=FINE)


