#!/usr/bin/env python3
"""
Draws the character states as line art, from real mushrooms.

On a panel with no colour, a picture of a gill attachment is not decoration — it is
the question. A reader in a wood can match a drawing against what is in their hand
faster than they can read "adnexed" and wonder whether that was the narrow one.

**Every drawing is of a named species that actually shows the character**, recorded in
EXEMPLARS below and emitted as Kotlin so the app can say what it drew. A generic
cartoon of "decurrent" teaches nothing; *Cantharellus* running down its own stem
teaches it in one look. Where a species is the textbook illustration of a character —
*Tricholoma* for a notched gill, *Amanita* for a sac volva — that is the one drawn.

What line art can carry honestly is silhouette, proportion and topology. That happens
to be exactly what these characters are: whether the gill reaches the stem, whether
the bulb has a rim, whether the tubes lift away from the cap. Colour and texture are
not attempted, because the panel has neither and the schema asks about them separately.

    python3 tools/make-art.py

Output is 96x96 vector drawables in app/src/main/res/drawable/, named
art_<character>_<value>.xml, stroke only. Drawn at about 56dp, so nothing finer than
a 3-unit gap survives — that is the constraint every drawing is built to.
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "app", "src", "main", "res", "drawable")
KT = os.path.join(HERE, "..", "app", "src", "main", "kotlin", "com",
                  "wanderwildwood", "kinokocho", "ui", "CharacterArt.kt")

# Lighter than the first pass. These started at 4.0/2.5/1.8 on the theory that an
# e-ink panel needs weight, and the drawings came out heavy and blunt — the owner compared
# them to a hand-drawn reference and the difference was line weight more than anything
# else. A pen drawing is thin and confident; thick strokes also close up small shapes,
# which is what wrecked the launcher icon. Legibility at 64px comes from clear shapes,
# not from fat lines.
STROKE = 2.8          # the silhouette
FINE = 1.9            # gills, tubes, cross-veins: things meant to read as many
HAIR = 1.3            # texture that must not compete with the silhouette
GROUND = 86.0

# The species each drawing is taken from, and what it is doing there. Written down
# because "based on a real mushroom" is a claim that has to be checkable, and because
# a reader who wants to know why the picture looks like that deserves an answer.
EXEMPLARS = {}


def drawn_from(name, species, why):
    EXEMPLARS[name] = (species, why)
    return name


# No android:tint here: the app themes with MMD, which does not carry
# ?attr/colorOnSurface, and aapt fails on every drawable if it is set. The Icon
# composable tints these at the call site instead, which is where the theme is.
HEADER = """<!-- Generated by tools/make-art.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="96dp"
    android:height="96dp"
    android:viewportWidth="96"
    android:viewportHeight="96">
"""
FOOTER = "</vector>\n"


def path(d, width=STROKE, fill=False, cap="round"):
    return (
        '    <path\n'
        f'        android:pathData="{d}"\n'
        f'        android:strokeColor="{"#00000000" if fill else "#FF000000"}"\n'
        f'        android:strokeWidth="{0 if fill else width}"\n'
        f'        android:fillColor="{"#FF000000" if fill else "#00000000"}"\n'
        f'        android:strokeLineCap="{cap}"\n'
        '        android:strokeLineJoin="round" />\n'
    )


def write(name, species, why, *paths):
    os.makedirs(OUT, exist_ok=True)
    assert re.fullmatch(r"[a-z0-9_]+", name), name
    drawn_from(name, species, why)
    with open(os.path.join(OUT, f"{name}.xml"), "w") as f:
        f.write(HEADER + "".join(paths) + FOOTER)


